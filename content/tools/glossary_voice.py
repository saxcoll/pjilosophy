INTRO = (
    "A working vocabulary for this sequence — the words the sittings actually force — not a dictionary of all philosophy. "
    "Read the pages first; these are margins. Later thinkers reuse or invert an earlier word; the links are the point."
)


def apply_voice(glossary: dict) -> list[str]:
    errors = []
    terms = glossary.get("terms") or []
    ids = {t["id"] for t in terms}
    missing = sorted(ids - set(VOICE))
    extra = sorted(set(VOICE) - ids)
    if missing:
        errors.append("voice missing: " + ", ".join(missing))
    if extra:
        errors.append("voice extra: " + ", ".join(extra))
    glossary["intro"] = INTRO
    for t in terms:
        pair = VOICE.get(t["id"])
        if not pair:
            continue
        t["short"] = pair[0]
        t["definition"] = pair[1]
    return errors


